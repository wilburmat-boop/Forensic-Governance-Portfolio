    # Count evidence rows
    evidence_rows = len(re.findall(r'<span class="evidence-link"', content))
    print(f"✓ Verified: {evidence_rows} evidence-linked rows in index.html")
    
    # Check for specific refs
    refs_to_check = ["B1", "SCR1", "VICT1", "GRC1", "GRC2", "GRC3", "CRO1", "U1", "M1", "U11"]
    for ref in refs_to_check:
        if f'>{ref}</span>' in content:
            print(f"  ✓ {ref} found")
        else:
            print(f"  ✗ {ref} NOT FOUND")

