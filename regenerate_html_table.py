def update_index_html(new_rows):
    """
    Find and replace the evidence table rows in index.html
    """
    # Read current index.html
    with open("index.html", "r", encoding="utf-8") as f:
        content = f.read()
    
    # Backup original
    with open("index.html.backup_before_regen", "w", encoding="utf-8") as f:
        f.write(content)
    print("✓ Backed up index.html to index.html.backup_before_regen")
    
    # Find the table section containing evidence rows
    # Pattern: from <!-- MASTER CHRONOLOGY --> to </table>
    pattern = r'(<!-- MASTER CHRONOLOGY -->.*?<tr><th>Date</th><th>Event</th><th>Evidence Ref</th></tr>)(.*?)(</table>)'
    
    def replacement(match):
        header = match.group(1)
        old_rows = match.group(2)
        footer = match.group(3)
        return header + "\n" + new_rows + "\n                " + footer
    
    updated_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    
    if updated_content == content:
        print("[ERROR] Could not find evidence table in index.html")
        return False
    
    # Write updated content
    with open("index.html", "w", encoding="utf-8") as f:
        f.write(updated_content)
    
    print("✓ Updated index.html with regenerated evidence table rows")
    return True

